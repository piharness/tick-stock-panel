/**
 * 市场常识 —— 「行业内确定性」的结构化知识库。
 *
 * 与上一版的关键差别：上一版是 21 条**平铺**条目，读者只能逐条记；这一版把条目
 * 挂到一条**五层因果链**上，并给每条补三样东西：
 *   · 常见误解 —— 大多数人实际信的那个错误版本是什么；
 *   · 自查入口 —— 这条结论在哪个页面/哪个数字上能被当场核对；
 *   · 实时锚点 —— 一条能用当天全市场数据算出来的小数字（见 anchors.ts）。
 *
 * 因果链（也是页面的骨架）：
 *   ① 规则边界 → ② 信息分布 → ③ 参与者动机 → ④ 市场结构 → ⑤ 结算与代价 →（回到①）
 *   规则定「能交易什么、能移动多少」；信息定「谁先定价」；动机定「价格落在哪」；
 *   结构定「出事时谁跑得掉」；结算定「代价落在谁头上」；代价再倒逼规则修订。
 * 一条常识如果无法被放进这条链上的某一格，它大概不是常识，而是话术。
 *
 * 设计纪律：
 *   1. 每条标注「确定性等级」：硬规则（交易所明文，可逐日计数）/ 强共识 / 概率倾向 / 经验。
 *   2. 每条标注「依据」：条款 / 数据口径 / 本项目实测，不写「业内普遍认为」。
 *   3. 规则会过时：涨跌幅、退市门槛都在 2024–2026 改过，条目写清生效时间。
 *   4. 算不出来的就说算不出来（例如摘帽率：本地库只有在市标的，见 settle-survivor）。
 */
import type { AnchorId } from './anchors'
import type { ProbeId } from './probes'

export type Certainty = 'hard-rule' | 'strong-consensus' | 'probabilistic' | 'heuristic'

export type LayerId = 'rule' | 'info' | 'player' | 'structure' | 'settle'

/** 条目之间的边。关系必须是可陈述的一句话，不能只写「相关」。 */
export type RelKind =
  /** 前者是后者的成因 */
  | 'leads'
  /** 前者要理解，得先理解后者 */
  | 'needs'
  /** 前者限定了后者的取值范围 */
  | 'limits'
  /** 两者互相矛盾，同时相信就是没想清楚 */
  | 'contradicts'

export interface Relation {
  to: string
  kind: RelKind
  note: string
}

export interface Layer {
  id: LayerId
  index: number
  label: string
  /** 这一层回答的问题 */
  question: string
  /** 这一层在因果链上的位置 */
  role: string
  /** 为什么下一层由此产生（最后一层回到第一层） */
  toNext: string
}

export interface KnowledgeItem {
  id: string
  layer: LayerId
  title: string
  /** 一句话结论（先给确定性，再给细节） */
  summary: string
  /** 展开后的完整解释 */
  body: string
  certainty: Certainty
  /** 依据：规则条款 / 数据口径 / 本项目实测 */
  basis: string
  /** 大多数人实际相信的那个错误版本 */
  misconception: string
  /** 这条结论在哪里能被当场核对 */
  check: string
  /** 规则生效时间 / 最近一次变动 */
  effective?: string
  /** 可用的实时锚点（见 anchors.ts 的 ALL_ANCHORS）——市场级，每天变 */
  anchor?: AnchorId
  /**
   * 可用的个股判据（见 probes.ts）——个股级，输入代码才算。
   * 与 anchor 的分工：anchor 回答「今天的市场是这样」，probe 回答「这只票是不是这样」。
   * 一条常识最多挂一个 probe：否则「点判定→跳条目」就不再是一对一。
   */
  probe?: ProbeId
  related: Relation[]
}

export interface Category {
  id: LayerId
  label: string
  hint: string
}

